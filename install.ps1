# UnlProxy - one command install (Windows).
#
#   irm https://raw.githubusercontent.com/a2z05/UnlProxy/master/install.ps1 | iex
#
# Installs into %LOCALAPPDATA%\UnlProxy, brings the pool up, and registers a
# logon task that runs the self-driving daemon. No admin needed.
$ErrorActionPreference = 'Stop'
# Windows PowerShell 5.1 defaults to TLS 1.0/1.1, which GitHub refuses
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$Dir  = if ($env:UNLPROXY_DIR) { $env:UNLPROXY_DIR } else { Join-Path $env:LOCALAPPDATA 'UnlProxy' }
$Raw  = if ($env:UNLPROXY_RAW) { $env:UNLPROXY_RAW } else { 'https://raw.githubusercontent.com/a2z05/UnlProxy/master' }
$Nodes = if ($env:UNLPROXY_NODES) { [int]$env:UNLPROXY_NODES } else { 3 }

function Say($m) { Write-Host "> $m" -ForegroundColor Red }

# --- deps -------------------------------------------------------------------
$py = Get-Command python -ErrorAction SilentlyContinue
if (-not $py) { $py = Get-Command python3 -ErrorAction SilentlyContinue }
if (-not $py) {
    Say 'python not found - installing with winget'
    winget install -e --id Python.Python.3.12 --accept-source-agreements --accept-package-agreements
    $py = (Get-Command python -ErrorAction SilentlyContinue)
    if (-not $py) { throw 'Python install failed - install Python 3.9+ from python.org and rerun' }
}
# the WindowsApps 'python' is a re-exec alias: it loses the working directory and
# then cannot find a relative script. Ask the interpreter where it really lives.
$real = (& $py.Source -c 'import sys; print(sys.executable)').Trim()
if ($real) { $py = Get-Command $real }

# --- files ------------------------------------------------------------------
Say "installing into $Dir"
New-Item -ItemType Directory -Force -Path $Dir, "$Dir\assets", "$Dir\scripts" | Out-Null
foreach ($f in 'warppool.py', 'ui.html', 'config.example.json', 'unlproxy.bat', 'unlp.cmd', 'assets/hero.svg', 'assets/architecture.svg') {
    $dest = Join-Path $Dir $f
    Invoke-WebRequest -UseBasicParsing -Uri "$Raw/$f" -OutFile $dest
    if ((Get-Item $dest).Length -lt 200) { throw "download failed or truncated: $f" }
}

# --- launcher on PATH -------------------------------------------------------
# `unlp` opens the control UI in the browser. Put it next to python so it is
# found from any shell without touching the user's PATH. The interpreter path is
# baked in: the WindowsApps 'python' alias loses the working directory.
$binDir = Split-Path $py.Source -Parent
$unlp = Join-Path $binDir 'unlp.cmd'
$launcher = @"
@echo off
rem UnlProxy launcher - generated by install.ps1
setlocal
pushd "$Dir"
if "%~1"=="" (
  "$($py.Source)" warppool.py ui
) else (
  "$($py.Source)" warppool.py %*
)
popd
"@
Set-Content -Path $unlp -Value $launcher -Encoding ASCII
Say "launcher: unlp  (in $binDir - opens the UI)"

# --- pool -------------------------------------------------------------------
Say "bringing $Nodes node(s) up (first run downloads usque and registers with Cloudflare)"
Push-Location $Dir
try {
    & $py.Source warppool.py config --nodes $Nodes --quiet
    & $py.Source warppool.py init
    if ($LASTEXITCODE -ne 0) { throw "init failed - see $Dir\nodes\*.log" }
    & $py.Source warppool.py status
} finally { Pop-Location }

# --- background daemon ------------------------------------------------------
# rotation is self-driving inside `daemon`; no cron-style tick task any more
$action = New-ScheduledTaskAction -Execute $py.Source -Argument '"warppool.py" daemon' -WorkingDirectory $Dir
$trigger = New-ScheduledTaskTrigger -AtLogOn
$set = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero)
Register-ScheduledTask -TaskName 'UnlProxy daemon' -Action $action -Trigger $trigger -Settings $set -Force | Out-Null
Start-ScheduledTask -TaskName 'UnlProxy daemon'
Say 'scheduled task: unlproxy daemon at logon (rotates on its own)'

Say 'done.'
Write-Host ""
Write-Host "  unlp   open the control UI in your browser"
Write-Host "  cli    cd `"$Dir`"; python warppool.py cli      # status, rotate, nodes, 9r"
Write-Host "  ui     cd `"$Dir`"; python warppool.py serve    # http://127.0.0.1:8180/"
Write-Host "  socks  127.0.0.1:18090 ... :$((18090 + $Nodes - 1))"
Write-Host "  run    `"$Dir\unlproxy.bat`""
